"""Export glyphs as a C font initializer."""

import re

from pixel_font_editor.model import Glyph


FONT_DECLARATION = re.compile(
    r"\bconst\s+font_t\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\{"
)


def extract_c_header(source: str) -> str:
    """Return all source text before the font_t declaration."""
    declaration = FONT_DECLARATION.search(source)
    if declaration is None:
        raise ValueError("no const font_t initializer was found")
    return source[: declaration.start()]


def render_c_font(name: str, glyphs: list[Glyph], header: str = "") -> str:
    """Render glyphs in the font_t initializer format."""
    identifier = re.sub(r"\W", "_", name)
    if not identifier or identifier[0].isdigit():
        identifier = f"font_{identifier}"
    if not glyphs:
        raise ValueError("at least one glyph is required")

    width = glyphs[0].width
    height = glyphs[0].height
    if any(glyph.width != width or glyph.height != height for glyph in glyphs):
        raise ValueError("all glyphs must have the same dimensions")

    lines = [
        f"const font_t {identifier} = {{",
        f"    .width = {width},",
        "    .glyphs = {",
    ]
    for index, glyph in enumerate(glyphs):
        description = " ".join(glyph.description.split())
        suffix = f" {description}" if description else ""
        lines.append(f"        // 0x{index:02X}{suffix}")
        lines.extend(f"        0b{row:0{width}b}," for row in glyph.rows) # type: ignore
    lines.append("    }};")
    if header and not header.endswith(("\n", "\r")):
        header += "\n"
    return header + "\n".join(lines) + "\n"


def parse_c_font(source: str) -> tuple[str, list[Glyph]]:
    """Parse a C initializer generated by this editor."""
    header = FONT_DECLARATION.search(source)
    if header is None:
        raise ValueError("no const font_t initializer was found")

    initializer_end = source.find("}};", header.end())
    if initializer_end < 0:
        raise ValueError("font initializer is not closed")
    initializer = source[header.end() : initializer_end]

    width_match = re.search(r"\.width\s*=\s*(\d+)\s*,", initializer)
    if width_match is None:
        raise ValueError("font width was not found")
    width = int(width_match.group(1))
    if not 1 <= width <= 32:
        raise ValueError("font width must be between 1 and 32")

    glyphs_match = re.search(r"\.glyphs\s*=\s*\{", initializer)
    if glyphs_match is None:
        raise ValueError("glyph data was not found")

    glyph_rows: list[list[int]] = []
    glyph_descriptions: list[str] = []
    current_index: int | None = None
    current_rows: list[int] = []
    current_description = ""

    def finish_glyph() -> None:
        if current_index is None:
            return
        expected_index = len(glyph_rows)
        if current_index != expected_index:
            if current_index < expected_index:
                problem = f"duplicate index 0x{current_index:02X}"
            else:
                problem = f"missing index 0x{expected_index:02X} before this glyph"
            raise ValueError(
                f"non-sequential glyph index: expected 0x{expected_index:02X}, "
                f"found 0x{current_index:02X} ({problem})"
            )
        if not current_rows:
            raise ValueError(f"glyph 0x{current_index:02X} has no rows")
        glyph_rows.append(current_rows.copy())
        glyph_descriptions.append(current_description)

    for raw_line in initializer[glyphs_match.end() :].splitlines():
        line = raw_line.strip()
        if not line:
            continue

        if line.startswith("//"):
            marker = re.fullmatch(r"//\s*0x([0-9A-Fa-f]+)(?:\s+(.*))?\s*", line)
            if marker is None:
                continue
            finish_glyph()
            current_index = int(marker.group(1), 16)
            current_rows = []
            current_description = (marker.group(2) or "").strip()
            continue

        row_match = re.fullmatch(r"0b([01]+)\s*,?", line)
        if row_match is None:
            if line.startswith("/*") or line.startswith("*") or line.endswith("*/"):
                continue
            raise ValueError(f"unsupported glyph row: {line}")
        if current_index is None:
            raise ValueError("binary rows must follow a // 0xNN glyph marker")

        bits = row_match.group(1)
        if len(bits) > width:
            raise ValueError(f"glyph row exceeds the declared width of {width}")
        current_rows.append(int(bits, 2))

    finish_glyph()
    if not glyph_rows:
        raise ValueError("font contains no glyphs")

    try:
        glyphs = [
            Glyph(width, len(rows), rows, description)
            for rows, description in zip(glyph_rows, glyph_descriptions)
        ]
    except ValueError as error:
        raise ValueError(f"invalid glyph dimensions: {error}") from error
    return header.group(1), glyphs